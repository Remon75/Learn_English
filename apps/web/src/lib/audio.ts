import { Howl } from 'howler';
import type { MediaRef } from '@sparkle/shared';

/**
 * Audio engine.
 *
 * Howler.js handles playback and the Web Audio API handles synthesis and
 * analysis. Two design rules drive this module:
 *
 *  1. Every sound is loaded from our own origin (`/media/...`). No CDN, no
 *     third-party streaming, no telemetry in the audio stack.
 *  2. Sound is always paired with a visual event. A child who cannot hear
 *     the device, or who has the volume turned down, still gets the same
 *     feedback through the visuals.
 *
 * ## Placeholder audio
 *
 * The repository ships *placeholder* audio: a short tone per word, not a
 * recording. Playing a tone for "cat" teaches a child nothing, so the app
 * speaks the word instead, using the Web Speech API of the device it is
 * running on.
 *
 * The media manifest (`/media/manifest.json`, generated by
 * `scripts/generate-media.mjs`) is the source of truth for that decision. It
 * lists every placeholder file together with the text it stands for. When a
 * real recording replaces a placeholder, the manifest stops listing it (or
 * the file name no longer matches) and the recording is played as-is.
 *
 * Speech synthesis runs entirely inside the browser and the operating
 * system: the app never sends the text anywhere.
 */

export type SoundName = 'tap' | 'correct' | 'wrong' | 'reward' | 'star';

interface ToneSpec {
  frequency: number;
  durationSec: number;
  type: OscillatorType;
}

const TONES: Record<SoundName, ToneSpec> = {
  tap: { frequency: 660, durationSec: 0.08, type: 'sine' },
  correct: { frequency: 880, durationSec: 0.18, type: 'sine' },
  wrong: { frequency: 220, durationSec: 0.22, type: 'triangle' },
  reward: { frequency: 1046, durationSec: 0.35, type: 'sine' },
  star: { frequency: 1568, durationSec: 0.12, type: 'sine' },
};

/* ----------------------------- Media manifest ---------------------------- */

interface ManifestEntry {
  /** The text the placeholder stands for. */
  text?: string;
  /** The generated file name, e.g. `hello.wav`. */
  file?: string;
  /** `false` once a real recording replaces the placeholder. */
  placeholder?: boolean;
}

interface MediaManifest {
  version: number;
  audio: Record<string, ManifestEntry>;
}

const MANIFEST_URL = '/media/manifest.json';

let manifest: MediaManifest | null = null;
let manifestRequest: Promise<MediaManifest | null> | null = null;

/**
 * Loads the media manifest once.
 *
 * The manifest is a small static file served from our own origin. It is
 * warmed at start-up so the very first word of a lesson is already spoken
 * rather than beeped.
 */
export function loadMediaManifest(): Promise<MediaManifest | null> {
  if (manifest) return Promise.resolve(manifest);
  if (!manifestRequest) {
    manifestRequest = fetch(MANIFEST_URL, { credentials: 'same-origin' })
      .then((res) => (res.ok ? (res.json() as Promise<MediaManifest>) : null))
      .then((data) => {
        manifest = data;
        return data;
      })
      .catch(() => null)
      .finally(() => {
        // Allow a retry: the first attempt may have failed while offline.
        manifestRequest = null;
      });
  }
  return manifestRequest;
}

/** Splits `/media/audio/hello.wav` into its id (`hello`) and file name. */
function mediaId(src: string): { id: string; file: string } {
  const file = src.slice(src.lastIndexOf('/') + 1);
  return { id: file.replace(/\.[^.]+$/, ''), file };
}

/**
 * Returns the manifest entry when the file is still a generated placeholder.
 *
 * A different file name means a real recording has taken the place of the
 * placeholder, and the recording is played instead of being spoken.
 */
function placeholderFor(src: string): ManifestEntry | null {
  if (!manifest) return null;
  const { id, file } = mediaId(src);
  const entry = manifest.audio?.[id];
  if (!entry) return null;
  if (entry.placeholder === false) return null;
  if (entry.file && entry.file !== file) return null;
  return entry;
}

/* ------------------------------ Playback --------------------------------- */

/** Cached Howl instances, keyed by media path. */
const cache = new Map<string, Howl>();
const enabled = { value: true };

export function setAudioEnabled(value: boolean): void {
  enabled.value = value;
}

export function isAudioEnabled(): boolean {
  return enabled.value;
}

function getHowl(src: string): Howl {
  const existing = cache.get(src);
  if (existing) return existing;

  const howl = new Howl({
    src: [src],
    format: ['mp3', 'ogg', 'wav'],
    preload: true,
    html5: false,
    onloaderror: (_id, error) => {
      // A missing asset must never break the lesson. The visual channel
      // carries the meaning on its own.
      console.warn(`[audio] could not load ${src}:`, error);
    },
  });
  cache.set(src, howl);
  return howl;
}

/** Plays a media file from the local media library. */
export function play(src: string, volume = 1): void {
  if (!enabled.value) return;
  const howl = getHowl(src);
  howl.play();
  if (volume !== 1) howl.volume(volume);
}

/* --------------------------- Speech synthesis ---------------------------- */

let preferredVoice: SpeechSynthesisVoice | null = null;

/**
 * Picks an English voice, preferring one that runs on the device.
 *
 * A `localService` voice is synthesised by the operating system, so the
 * text never leaves the machine. Cloud voices are only used when the
 * device offers nothing else.
 */
function pickVoice(): SpeechSynthesisVoice | null {
  if (typeof speechSynthesis === 'undefined') return null;
  const voices = speechSynthesis.getVoices();
  if (!voices.length) return null;
  const english = voices.filter((voice) => voice.lang?.toLowerCase().startsWith('en'));
  return english.find((voice) => voice.localService) ?? english[0] ?? null;
}

if (typeof speechSynthesis !== 'undefined') {
  const rememberVoices = () => {
    preferredVoice = pickVoice();
  };
  rememberVoices();
  // Voice lists load asynchronously in most browsers.
  if (typeof speechSynthesis.addEventListener === 'function') {
    speechSynthesis.addEventListener('voiceschanged', rememberVoices);
  } else {
    speechSynthesis.onvoiceschanged = rememberVoices;
  }
}

/**
 * Speaks text through the Web Speech API.
 *
 * Returns `true` when the utterance was handed to the browser, so callers
 * can fall back to file playback when speech is unavailable.
 */
function trySpeak(text: string, lang = 'en-US'): boolean {
  if (!enabled.value) return false;
  if (typeof speechSynthesis === 'undefined' || typeof SpeechSynthesisUtterance === 'undefined') {
    return false;
  }
  const trimmed = text.trim();
  if (!trimmed) return false;

  try {
    speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(trimmed);
    utterance.lang = lang;
    utterance.rate = 0.85;
    utterance.pitch = 1.05;

    const voice = preferredVoice ?? pickVoice();
    if (voice) {
      utterance.voice = voice;
      preferredVoice = voice;
    }

    speechSynthesis.speak(utterance);
    return true;
  } catch {
    // The Web Speech API is a progressive enhancement, never a requirement.
    return false;
  }
}

/** Speaks text through the Web Speech API. */
export function speak(text: string, lang = 'en-US'): void {
  trySpeak(text, lang);
}

/**
 * Plays a media reference.
 *
 * Placeholder audio is *spoken* rather than beeped, using the transcript
 * of the activity when it has one and the manifest text otherwise. Real
 * recordings are always played as files.
 */
export function playMedia(ref: MediaRef, volume = 1): void {
  if (!enabled.value) return;

  const placeholder = placeholderFor(ref.src);
  if (placeholder) {
    const text = ref.transcript?.trim() || placeholder.text?.trim();
    if (text && trySpeak(text)) return;
  }

  // A real recording, or a device without speech synthesis: play the file.
  if (typeof speechSynthesis !== 'undefined') speechSynthesis.cancel();
  play(ref.src, volume);
}

let audioContext: AudioContext | null = null;

function getAudioContext(): AudioContext | null {
  if (typeof window === 'undefined') return null;
  if (!audioContext) {
    const Ctor =
      window.AudioContext ??
      (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
    if (!Ctor) return null;
    audioContext = new Ctor();
  }
  return audioContext;
}

/**
 * Plays a short synthesised tone.
 *
 * Reward sounds are generated on the device rather than shipped as files:
 * it keeps the offline bundle small and means no audio ever leaves the
 * machine.
 */
export function playTone(name: SoundName): void {
  if (!enabled.value) return;
  const ctx = getAudioContext();
  if (!ctx) return;
  if (ctx.state === 'suspended') void ctx.resume();

  const spec = TONES[name];
  const now = ctx.currentTime;
  const oscillator = ctx.createOscillator();
  const gain = ctx.createGain();

  oscillator.type = spec.type;
  oscillator.frequency.setValueAtTime(spec.frequency, now);
  if (name === 'reward') {
    oscillator.frequency.exponentialRampToValueAtTime(spec.frequency * 1.5, now + spec.durationSec);
  }

  gain.gain.setValueAtTime(0.0001, now);
  gain.gain.exponentialRampToValueAtTime(0.25, now + 0.01);
  gain.gain.exponentialRampToValueAtTime(0.0001, now + spec.durationSec);

  oscillator.connect(gain);
  gain.connect(ctx.destination);
  oscillator.start(now);
  oscillator.stop(now + spec.durationSec);
}

/** Stops everything. Used when leaving a screen or on a parent lock. */
export function stopAll(): void {
  for (const howl of cache.values()) howl.stop();
  if (typeof speechSynthesis !== 'undefined') speechSynthesis.cancel();
}

/**
 * Measures the loudness of the microphone input.
 *
 * Used for a visual "loudness meter" so a child can see that the app is
 * hearing them. It returns 0..1 and never stores or transmits the audio.
 */
export function createLoudnessMeter(stream: MediaStream): {
  level: () => number;
  stop: () => void;
} {
  const ctx = getAudioContext();
  if (!ctx) return { level: () => 0, stop: () => {} };

  const source = ctx.createMediaStreamSource(stream);
  const analyser = ctx.createAnalyser();
  analyser.fftSize = 256;
  source.connect(analyser);

  const data = new Uint8Array(analyser.frequencyBinCount);
  let current = 0;

  const tick = () => {
    analyser.getByteFrequencyData(data);
    let sum = 0;
    for (let i = 0; i < data.length; i += 1) sum += data[i] ?? 0;
    current = Math.min(1, sum / data.length / 128);
  };

  const interval = window.setInterval(tick, 100);

  return {
    level: () => current,
    stop: () => {
      window.clearInterval(interval);
      source.disconnect();
      analyser.disconnect();
    },
  };
}
